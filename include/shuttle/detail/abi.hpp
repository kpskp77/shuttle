#pragma once

// Installed ABI header — **second public layer** (stable ABI): both its path
// and its content are version-managed. User code should not include it
// directly (the public entry points are publisher.hpp / subscription.hpp),
// but the public templates (Publisher<T> / subscribe<T>) must see these
// declarations in the user's TU.
// Content boundary: this file holds only declarations and lightweight
// templates (TypeOps / type_ops<T>); implementations are split by "which
// handle they return" across TUs: the publish side (pub_* / topic_*) lives
// with Publication in src/publication.cpp; the subscribe side (sub_*) lives
// with Subscription in src/subscription.cpp.
// Changing anything here is an ABI change: libshuttle and all consumers must
// be recompiled together.

#include <cstddef>
#include <functional>
#include <memory>
#include <shuttle/codec.hpp>
#include <shuttle/meta.hpp>
#include <shuttle/types.hpp>
#include <string>
#include <vector>

namespace shuttle {

class Publication;
class Subscription;
class Trigger;

namespace detail {

// ── TypeOps: per-type runtime operation table (generated by type_ops<T>()) ──
struct TypeOps {
  const char* tag;  // type tag: the type-binding identity of a topic (consistent across languages)

  // nullptr means the type is not cross-language capable (no SHUTTLE_REFLECT):
  // delivering to an SV subscriber or a byte subscriber (subscribe_bytes)
  // throws PublishError — `publish_now` throws straight to the caller;
  // `serial`/`concurrent` record it as that subscriber's Failure (rethrown at
  // `Publication::result()`).
  std::vector<std::byte> (*encode)(const void* obj);
  // materialize an object from a byte stream (SV → C++ direction); nullptr as above.
  std::shared_ptr<const void> (*decode)(const std::vector<std::byte>&);
};

template <typename T>
const TypeOps* type_ops() {
  static const std::string tag = type_tag_of<T>();
  static const TypeOps ops{
      tag.c_str(),
      []() -> std::vector<std::byte> (*)(const void*) {
        if constexpr (has_codec_v<T>) {
          return [](const void* p) { return encode(*static_cast<const T*>(p)); };
        }
        return nullptr;
      }(),
      []() -> std::shared_ptr<const void> (*)(const std::vector<std::byte>&) {
        if constexpr (has_codec_v<T>) {
          return [](const std::vector<std::byte>& b) -> std::shared_ptr<const void> {
            return std::make_shared<const T>(decode<T>(b));
          };
        }
        return nullptr;
      }(),
  };
  return &ops;
}

// Type-erased subscriber callback: p points to a materialized T (guaranteed non-null)
using ErasedCallback = std::function<void(const void* p, const Meta&)>;

// ── broker interaction interface (defined in src/publication.cpp and src/subscription.cpp) ──

// Declare the topic's type binding; throws TypeMismatchError on conflict with an existing binding.
void topic_declare(const std::string& topic, const TypeOps* ops);

// pub_now (= the public API's publish_now): synchronously invokes all subscribers
// with a nonblocking entry on the publisher's stack. The message has already
// been copied at the call site (snapshot semantics). See NowPolicy for policy.
// The return value covers the frame's **targets** (the nonblocking part has
// finished when it returns; the deferred part runs on the background serial
// chain); targets skipped by `skip` are not counted in `expected` and surface
// only in `skipped()` and the `skipped` component of `dropped()`; `reject`
// throws CapabilityError directly and yields no return value.
Publication pub_now(const std::string& topic, std::shared_ptr<const void> msg, const TypeOps* ops,
                    NowPolicy policy);

// pub_serial (= publish_serial): background single-chain, in-order callbacks;
// pub_concurrent (= publish_concurrent): background, one task per subscriber,
// concurrent callbacks. Both deliver to **all** matching subscribers (each
// subscriber is invoked once, on the one entry it registered). With an empty
// trigger they start immediately; both return the completion handle right away.
Publication pub_serial(const std::string& topic, std::shared_ptr<const void> msg,
                       const TypeOps* ops, Trigger trig);
Publication pub_concurrent(const std::string& topic, std::shared_ptr<const void> msg,
                           const TypeOps* ops, Trigger trig);

// Subscribe: topic_pattern supports wildcards ("*" matches one level, ">"
// matches at least one further level).
Subscription sub_typed(std::string topic_pattern, const TypeOps* ops, ErasedCallback cb,
                       Capability cap, SubOptions opts);
Subscription sub_raw(std::string topic_pattern, ByteCallback cb, Capability cap, SubOptions opts);

// retained (latched): once enabled, new subscribers immediately receive the latest frame
void topic_set_retained(const std::string& topic, bool on);
bool topic_retained(const std::string& topic);

}  // namespace detail
}  // namespace shuttle
